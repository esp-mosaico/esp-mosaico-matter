inline constexpr uint32_t kAudioSampleRate = 48000;
inline constexpr uint8_t kAudioChannels = 1;
inline constexpr std::array<uint8_t, 3> kAudioBitDepths{ 16, 24, 32 };
inline constexpr uint32_t kAudioBitRate = 20000;
inline constexpr uint32_t kMinAudioBitRate = 6000;
inline constexpr uint32_t kMaxAudioBitRate = 128000;
inline constexpr uint32_t kAudioFrameDurationMs = 20;
inline constexpr size_t kMaxAudioPacketSize = kMaxAudioBitRate * kAudioFrameDurationMs / 8000;

inline bool SupportsAudioFormat(uint8_t channels, uint32_t sample_rate, uint8_t bit_depth, uint32_t bit_rate)
{
    bool supported_depth = false;
    for (auto depth : kAudioBitDepths) supported_depth |= depth == bit_depth;
    return channels == kAudioChannels && sample_rate == kAudioSampleRate && supported_depth &&
        bit_rate >= kMinAudioBitRate && bit_rate <= kMaxAudioBitRate;
}

inline size_t BuildOpusSilencePacket(uint32_t bit_rate, std::array<uint8_t, kMaxAudioPacketSize> &packet)
{
    if (bit_rate < kMinAudioBitRate || bit_rate > kMaxAudioBitRate) return 0;
    const size_t size = bit_rate * kAudioFrameDurationMs / 8000;
    packet.fill(0);
    // Reframe {0xf8, 0xff, 0xfe} as one padded CBR frame (RFC 6716 section 3.2.5).
    // Each padding-length byte of 255 accounts for 254 zero bytes plus another
    // length byte. Include that extra byte when sizing the packet.
    packet[0] = 0xfb;
    packet[1] = 0x41;
    size_t padding = size - 5;
    size_t index = 2;
    while (padding >= 255) {
        packet[index++] = 255;
        padding -= 255;
    }
    packet[index++] = static_cast<uint8_t>(padding);
    packet[index++] = 0xff;
    packet[index] = 0xfe;
    return size;
}

